     */
    fun stemWord(word: String): String {
        val clean = word.lowercase().trim()
        return when {
            clean == "chick" || clean == "chkn" -> "chicken"
            clean == "thighs" -> "thigh"
            clean == "breasts" -> "breast"
            clean == "potatoes" || clean == "spuds" || clean == "spud" -> "potato"
            clean == "tomatoes" -> "tomato"
            clean == "eggs" -> "egg"
            clean == "mince" -> "minced"
            clean == "sausages" -> "sausage"
            clean == "medallions" -> "medallion"
            clean == "rashers" -> "rasher"
            clean == "veg" || clean == "veggies" -> "vegetable"
            clean.endsWith("ies") && clean.length > 4 -> clean.dropLast(3) + "y"
            clean.endsWith("es") && clean.length > 4 && !clean.endsWith("ses") -> clean.dropLast(2)
            clean.endsWith("s") && clean.length > 3 && !clean.endsWith("ss") -> clean.dropLast(1)
            else -> clean
        }
    }

    /**
     * Searches the local curated UK/Irish staple database with token-based relevance scoring.
     * Features full English plural/singular stemming, alias expansion, and exact phrase boosting.
     */
    fun search(query: String): List<NormalizedOffProduct> {
        val cleanQuery = query.trim().lowercase()
        if (cleanQuery.isEmpty()) return emptyList()

        val rawTokens = cleanQuery.split(Regex("""[\s,.-]+""")).filter { it.isNotEmpty() }
        if (rawTokens.isEmpty()) return emptyList()

        val stemmedTokens = rawTokens.map { stemWord(it) }

        return staples.mapNotNull { staple ->
            val score = scoreProductRelevance(
                product = staple,
                rawTokens = rawTokens,
                stemmedTokens = stemmedTokens,
                cleanQuery = cleanQuery
            )
            if (score > 0) staple to score else null
        }
        .sortedByDescending { it.second }
        .map { it.first }
    }

    /**
     * Universal multi-field relevance scorer used across Staples, Local History, and Remote Open Food Facts.
     */
    fun scoreProductRelevance(
        product: NormalizedOffProduct,
        rawTokens: List<String>,
        stemmedTokens: List<String>,
        cleanQuery: String
    ): Int {
        val nameLower = product.name.lowercase()
        val brandLower = (product.brand ?: "").lowercase()
        val combinedNameAndBrand = if (brandLower.isNotBlank() && !nameLower.contains(brandLower)) {
            "$brandLower $nameLower"
        } else {
            nameLower
        }
        val ingredientsLower = product.ingredientsText.lowercase()

        val nameWords = combinedNameAndBrand.split(Regex("""[\s,./()—-]+""")).filter { it.isNotEmpty() }
        val nameStemmedWords = nameWords.map { stemWord(it) }

        var score = 0
        var matchedTokens = 0

        for (i in rawTokens.indices) {
            val rawToken = rawTokens[i]
            val stemmedToken = stemmedTokens[i]

            var tokenMatched = false

            // 1. Exact match on raw token in name/brand words
            if (nameWords.contains(rawToken)) {
                score += 50
                tokenMatched = true
            }
            // 2. Stemmed match in name/brand words (e.g. "thighs" -> "thigh", "chick" -> "chicken")
            else if (nameStemmedWords.contains(stemmedToken)) {
                score += 45
                tokenMatched = true
            }
            // 3. Prefix match on words (e.g. "chick" matching "chicken")
            else if (nameWords.any { it.startsWith(rawToken) && rawToken.length >= 4 }) {
                score += 35
                tokenMatched = true
            }
            // 4. Substring match in full name or brand
            else if (combinedNameAndBrand.contains(rawToken) || combinedNameAndBrand.contains(stemmedToken)) {
                score += 25
                tokenMatched = true
            }
            // 5. Match in ingredients / aliases text
            else if (ingredientsLower.contains(rawToken) || ingredientsLower.contains(stemmedToken)) {
                score += 15
                tokenMatched = true
            }

            if (tokenMatched) {
                matchedTokens++
            }
        }

        if (matchedTokens == 0) return 0

        // High boost if ALL query tokens matched
        if (matchedTokens == rawTokens.size) {
            score += 150
        } else {
            // If query has multiple tokens, require high token coverage or penalize missing tokens
            val coverageRatio = matchedTokens.toDouble() / rawTokens.size.toDouble()
            if (rawTokens.size >= 3 && coverageRatio < 0.5) {
                // Reject noisy 1-word matches on 3+ word specific searches
                return 0
            }
            score -= (rawTokens.size - matchedTokens) * 25
        }

        // High boost for exact phrase match in the product name or brand+name
        if (combinedNameAndBrand.contains(cleanQuery)) {
            score += 100
            if (nameLower.startsWith(cleanQuery) || nameLower.contains("virgin $cleanQuery") || nameLower.contains("pure $cleanQuery")) {
                score += 40
            }
        }

        // Exact brand match boost
        if (brandLower.isNotBlank() && rawTokens.any { brandLower.contains(it) && it.length >= 3 }) {
            score += 65
        }

        // Penalize secondary ingredients (e.g. "Tuna in Olive Oil" when searching "olive oil")
        if (nameLower.contains(" in $cleanQuery") || (nameLower.contains(" in ") && !cleanQuery.contains(" in "))) {
            score -= 60
        }

        // Boost raw/fresh cooking cuts over cooked variants unless user explicitly searched "cooked"
        val wantsCooked = rawTokens.any { it == "cooked" || it == "grilled" || it == "roasted" }
        if (nameLower.contains("cooked") && !wantsCooked) {
            score -= 40
        }

        return score
    }
